// دالة للحصول على كلمات مفتاحية مجمعة لأي قسم
export const getKeywordsForSection = (section: keyof typeof platformKeywords): string => {
  return [...platformKeywords.main, ...platformKeywords[section]].join(", ");
};

// دالة للحصول على جميع الكلمات المفتاحية
export const getAllKeywords = (): string => {
  return Object.values(platformKeywords)
    .flat()
    .join(", ");
};

// إحصائيات الكلمات المفتاحية
export const getKeywordStats = () => {
  const stats: Record<string, number> = {};
  let total = 0;
  
  Object.entries(platformKeywords).forEach(([section, keywords]) => {
    stats[section] = keywords.length;
    total += keywords.length;
  });
  
  return { ...stats, total };
};
