const AGENTS_STORAGE_KEY = 'galaxy_platform_ai_agents_registry_v1';

export class PlatformAIAgentsService {
  private static agents: PlatformAIAgent[] = [];

  public static initialize(): PlatformAIAgent[] {
    if (typeof window === 'undefined') return INITIAL_AI_AGENTS;
    try {
      const stored = localStorage.getItem(AGENTS_STORAGE_KEY);
      if (stored) {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed) && parsed.length >= 80) {
          this.agents = parsed;
          return this.agents;
        }
      }
    } catch (e) {
      console.warn('Failed to load stored agents registry:', e);
    }
    this.agents = INITIAL_AI_AGENTS;
    this.save();
    return this.agents;
  }

  public static getAllAgents(): PlatformAIAgent[] {
    if (this.agents.length === 0) {
      return this.initialize();
    }
    return this.agents;
  }

  public static toggleAgentBoost(agentId: string): PlatformAIAgent | undefined {
    const agent = this.agents.find(a => a.id === agentId);
    if (!agent) return undefined;

    agent.isBoosted = !agent.isBoosted;
    agent.status = agent.isBoosted ? 'turbo_boosted' : 'active';
    if (agent.isBoosted) {
      agent.maxOutputTokens = Math.max(agent.maxOutputTokens, 16384);
      agent.contextWindow = '2,000,000 Tokens';
      agent.accuracyRate = Math.min(99.9, +(agent.accuracyRate + 0.2).toFixed(1));
    }
    this.save();
    return agent;
  }

  public static boostAllAgents(): void {
    this.agents = this.agents.map(a => ({
      ...a,
      isBoosted: true,
      status: 'turbo_boosted' as const,
      maxOutputTokens: Math.max(a.maxOutputTokens, 16384),
      contextWindow: '2,000,000 Tokens',
      accuracyRate: Math.min(99.9, +(a.accuracyRate + 0.2).toFixed(1))
    }));
    this.save();
  }

  public static logAgentQuery(agentId: string, log: Omit<AgentActivityLog, 'id' | 'timestamp'>): void {
    const agent = this.agents.find(a => a.id === agentId);
    if (!agent) return;

    agent.totalQueries += 1;
    const newLog: AgentActivityLog = {
      id: `log-${Date.now()}-${Math.random().toString(36).substr(2, 4)}`,
      timestamp: 'الآن',
      ...log
    };
    agent.recentLogs = [newLog, ...(agent.recentLogs || []).slice(0, 15)];
    this.save();
  }

  private static save(): void {
    try {
      localStorage.setItem(AGENTS_STORAGE_KEY, JSON.stringify(this.agents));
      window.dispatchEvent(new CustomEvent('galaxy_ai_agents_registry_updated', { detail: this.agents }));
    } catch (e) {
      console.warn('Failed to persist agents registry:', e);
    }
  }
}
