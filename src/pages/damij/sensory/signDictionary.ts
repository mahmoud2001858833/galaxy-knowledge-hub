// ============== إزالة التشكيل والتطبيع ==============
export const stripDiacritics = (s: string) =>
  s.replace(/[\u064B-\u0652\u0670\u0640]/g, '');

export const normalizeWord = (raw: string): string => {
  if (!raw) return '';
  let w = stripDiacritics(raw)
    .replace(/[^\u0600-\u06FF\s]/g, '')
    .trim();
  if (!w) return '';
  // تطابق دقيق أو مرادف
  if (SIGN_DICT[w]) return w;
  if (SIGN_SYNONYMS[w]) return SIGN_SYNONYMS[w];
  // تطبيع الحروف الشائعة
  const folded = w
    .replace(/[إأآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي');
  if (SIGN_SYNONYMS[folded]) return SIGN_SYNONYMS[folded];
  if (SIGN_DICT[folded]) return folded;
  return w;
};

// إزالة "ال" التعريف ولاحقات بسيطة (ون/ين/ات/ها/ك/كم/نا/ه)
export const stemWord = (w: string): string => {
  let s = w;
  if (s.startsWith('ال') && s.length > 3) s = s.slice(2);
  s = s.replace(/(ون|ين|ات|تين|تان)$/u, '');
  s = s.replace(/(ها|هم|هن|كم|كن|نا|ه|ك|ي)$/u, '');
  return s || w;
};

