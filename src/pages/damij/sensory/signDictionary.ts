// ============== Lookup with fallback ==============
export type SignLookup =
  | { kind: 'word'; gesture: SignGesture }
  | { kind: 'spell'; letters: { letter: string; sign: LetterSign }[] }
  | { kind: 'unknown' };

export const lookupSign = (rawWord: string): SignLookup => {
  const norm = normalizeWord(rawWord);
  if (!norm) return { kind: 'unknown' };
  if (SIGN_DICT[norm]) return { kind: 'word', gesture: SIGN_DICT[norm] };
  // جذع
  const stem = stemWord(norm);
  if (SIGN_DICT[stem]) return { kind: 'word', gesture: SIGN_DICT[stem] };
  if (SIGN_SYNONYMS[stem] && SIGN_DICT[SIGN_SYNONYMS[stem]])
    return { kind: 'word', gesture: SIGN_DICT[SIGN_SYNONYMS[stem]] };
  // تهجئة
  const letters: { letter: string; sign: LetterSign }[] = [];
  for (const ch of norm) {
    const s = ARABIC_LETTER_SIGNS[ch];
    if (s) letters.push({ letter: ch, sign: s });
  }
  if (letters.length) return { kind: 'spell', letters };
  return { kind: 'unknown' };
};

export type SignToken =
  | { word: string; kind: 'word'; gesture: SignGesture }
  | { word: string; kind: 'spell'; letters: { letter: string; sign: LetterSign }[] }
  | { word: string; kind: 'unknown' };

// Tokenize a sentence: try 2-word phrases first
export const tokenizeSigns = (text: string): SignToken[] => {
  const raw = text.split(/\s+/).filter(Boolean);
  const out: SignToken[] = [];
  let i = 0;
  while (i < raw.length) {
    if (i + 1 < raw.length) {
      const pair = `${normalizeWord(raw[i])} ${normalizeWord(raw[i + 1])}`;
      if (SIGN_DICT[pair]) {
        out.push({ word: `${raw[i]} ${raw[i + 1]}`, kind: 'word', gesture: SIGN_DICT[pair] });
        i += 2; continue;
      }
    }
    const lk = lookupSign(raw[i]);
    if (lk.kind === 'word')   out.push({ word: raw[i], kind: 'word',  gesture: lk.gesture });
    else if (lk.kind === 'spell') out.push({ word: raw[i], kind: 'spell', letters: lk.letters });
    else out.push({ word: raw[i], kind: 'unknown' });
    i++;
  }
  return out;
};

